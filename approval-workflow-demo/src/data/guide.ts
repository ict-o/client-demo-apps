/** 現在のパスに対応する「かんたん説明」を返す */
export function helpFor(pathname: string): ScreenHelp | undefined {
  const found = SCREEN_HELP.find(h => {
    const regex = new RegExp(`^${h.pattern.replace(/:[^/]+/g, '[^/]+')}$`);
    return regex.test(pathname);
  });
  return found?.help;
}
